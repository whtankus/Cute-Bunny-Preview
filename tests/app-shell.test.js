const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const html = read('index.html');
const app = read('app.js');
const worker = read('sw.js');

test('app shell contains its essential page and session entry points', () => {
  for (const id of [
    'appLoader', 'app', 'mainContent', 'content', 'nav',
    'authGate', 'authForm', 'authEmail', 'authPass', 'profileGate', 'globalAudio'
  ]) {
    assert.ok(html.includes('id="' + id + '"') || html.includes("id='" + id + "'"), 'Missing #' + id);
  }
});

test('HTML element IDs are unique', () => {
  const ids = [...html.matchAll(/\bid=["']([^"']+)["']/g)].map(match => match[1]);
  const duplicates = [...new Set(ids.filter((id, index) => ids.indexOf(id) !== index))];
  assert.deepEqual(duplicates, [], 'Duplicate IDs: ' + duplicates.join(', '));
});

test('main navigation exposes the five supported app sections', () => {
  const pages = [...html.matchAll(/data-page=["']([^"']+)["']/g)].map(match => match[1]);
  assert.deepEqual(pages, ['home', 'gallery', 'music', 'notes', 'friends']);
  assert.match(html, /<nav\b[^>]*aria-label=["']Main navigation["']/);
});

test('all local HTML assets exist or are generated by the preview build', () => {
  const refs = [...html.matchAll(/(?:src|href)=["'](?!https?:|#|data:|javascript:)([^"'?#]+)(?:\?[^"']*)?["']/g)]
    .map(match => match[1])
    .filter(ref => ref !== './' && ref !== '.');
  for (const ref of refs) {
    if (ref === 'supabase-config.js') {
      assert.match(read('scripts/build-preview.js'), /writeFileSync\(path\.join\(output, ['"]supabase-config\.js['"]/);
      continue;
    }
    assert.ok(fs.existsSync(path.join(root, ref)), 'Missing local asset: ' + ref);
  }
});

test('app bootstraps session restoration and opens authentication without a welcome screen', () => {
  assert.match(app, /async function restoreSession\s*\(/);
  assert.match(app, /restoreSession\(\);/);
  assert.match(app, /openAuth\(['"]login['"]\)/);
  assert.doesNotMatch(html, /id=["']welcome["']/);
  assert.match(html, /id=["']appLoader["']/);
});

test('service worker uses network-first shell updates with an offline fallback', () => {
  assert.match(worker, /fetch\(request, \{ cache: ['"]no-store['"] \}\)/);
  assert.match(worker, /cache\.match\(['"]\.\/index\.html['"]\)/);
  assert.match(worker, /cute-bunny-shell-/);
});
